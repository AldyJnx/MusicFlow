-- Initial classification for the legacy catalog, whose artist and track genre
-- fields were previously empty. New and edited artists keep using the admin UI.
UPDATE "artists"
SET "genres" = ARRAY[
  CASE LOWER("name")
    WHEN '50cent' THEN 'Hip-Hop'
    WHEN 'afrodisiaco' THEN 'Urbano'
    WHEN 'amen' THEN 'Rock'
    WHEN 'bareto' THEN 'Fusión peruana'
    WHEN 'billie eilish' THEN 'Pop alternativo'
    WHEN 'bruno mars' THEN 'Pop'
    WHEN 'camila' THEN 'Pop latino'
    WHEN 'cristian castro' THEN 'Balada latina'
    WHEN 'cuco' THEN 'Indie pop'
    WHEN 'doja cat' THEN 'Pop rap'
    WHEN 'dua lipa' THEN 'Pop'
    WHEN 'elton john, dua lipa' THEN 'Pop'
    WHEN 'eminem' THEN 'Hip-Hop'
    WHEN 'enanitos verdes' THEN 'Rock en español'
    WHEN 'frankie ruíz' THEN 'Salsa'
    WHEN 'gonzalo genek' THEN 'Hip-Hop peruano'
    WHEN 'gonzalo genek, once' THEN 'Hip-Hop peruano'
    WHEN 'gonzalo genek, once, kaeve [m2h]' THEN 'Hip-Hop peruano'
    WHEN 'grupo 5' THEN 'Cumbia peruana'
    WHEN 'guns n'' roses' THEN 'Rock'
    WHEN 'gustavo cerati' THEN 'Rock en español'
    WHEN 'j balvin' THEN 'Reggaetón'
    WHEN 'juanes' THEN 'Pop latino'
    WHEN 'justin bieber' THEN 'Pop'
    WHEN 'katy perry' THEN 'Pop'
    WHEN 'luis miguel' THEN 'Balada latina'
    WHEN 'maluma' THEN 'Reggaetón'
    WHEN 'marc anthony' THEN 'Salsa'
    WHEN 'marron 5' THEN 'Pop rock'
    WHEN 'michael jackson' THEN 'Pop'
    WHEN 'paulo londra' THEN 'Trap latino'
    WHEN 'python bachatas' THEN 'Bachata'
    WHEN 'queen' THEN 'Rock'
    WHEN 'reik' THEN 'Pop latino'
    WHEN 'rio' THEN 'Rock en español'
    WHEN 'romeo santos' THEN 'Bachata'
    WHEN 'sean paul' THEN 'Dancehall'
    WHEN 'the beatles' THEN 'Rock'
    WHEN 'the black eyed peas' THEN 'Pop'
    WHEN 'the smiths' THEN 'Rock alternativo'
    WHEN 'the weeknd' THEN 'R&B'
    WHEN 'the black eyed peas' THEN 'Pop'
    WHEN 'unknown artist' THEN 'Sin clasificar'
    WHEN 'wisin y yandel' THEN 'Reggaetón'
    WHEN 'zen' THEN 'Rock peruano'
    ELSE 'Sin clasificar'
  END
]
WHERE CARDINALITY("genres") = 0;
